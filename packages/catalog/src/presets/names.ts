/** The bodies with `preset` set to the id wherever the id is a preset name and no preset is given. */
export const fillPresets = (bodies: Body[]): Body[] =>
    bodies.map((body) =>
        PRESET_NAMES.includes(body.id) && body.preset === undefined
            ? { ...body, preset: body.id }
            : body,
    );
